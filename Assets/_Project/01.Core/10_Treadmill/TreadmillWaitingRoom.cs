//      대신 Treadmill_Preview 씬에 '대기실 그리드'를 실제 오브젝트로 만들어 두고(바닥·벽 등),
//      이 컴포넌트를 그 루트에 붙여 '이게 대기실이다'라고 표시만 한다.
