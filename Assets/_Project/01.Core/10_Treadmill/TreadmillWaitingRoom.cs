using UnityEngine;

/// <summary>씬에 배치한 '대기실 그리드' 오브젝트임을 표시하는 마커(로직 없음).</summary>
[DisallowMultipleComponent]
public class TreadmillWaitingRoom : MonoBehaviour
{
    /// <summary>대기실 표시/숨김(도로가 호출). 오브젝트 자체를 켜고 끈다.</summary>
    public void Show(bool on)
    {
        if (gameObject.activeSelf != on) gameObject.SetActive(on);
    }
}
